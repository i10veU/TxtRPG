import assert from 'node:assert/strict';
import { createInitialState, step, view, validateState, checkDataCompatibility } from '../../web/v2/core/engine.js';
import { buildSaveRecord, parseLoadedRecord } from '../../web/v2/storage/idb.js';
import { worldData } from '../../web/v2/data/world.js';
const P = actionId => ({ type: 'perform', actionId });
const me = s => s.actors[s.player.actorId];
const can = (s, id) => view(s, worldData).actions.some(a => a.actionId === id && a.available);
const save = s => parseLoadedRecord(JSON.parse(JSON.stringify(buildSaveRecord('gallery-aftermath', s, { savedAt: 1 }))));
function run(s, action) {
  const result = step(s, action, worldData);
  assert.ok(!result.events.some(e => e.type === 'action.rejected'), JSON.stringify(result.events));
  assert.deepEqual(validateState(result.state), []);
  assert.deepEqual(checkDataCompatibility(result.state, worldData), []);
  return result.state;
}
const initial = createInitialState({ worldSeed: 'gallery-aftermath-497', data: worldData }).state;
assert.equal(can(initial, 'act_gallery_read_watch_records'), false, 'unvisited/uncleared gallery must not expose the aftermath');
const base = structuredClone(initial);
me(base).locationId = 'loc_ruins_gallery';
me(base).inventory.item_lantern = 1;
me(base).money = 12;
me(base).growth.growth_wanderer.resources.stamina = { current: 12, max: 12 };
base.flags = { ...base.flags, ruins_watch_gallery_open: true, ruins_gallery_secured: true,
  gallery_brute_defeated: true, gallery_scout_defeated: true,
  ruins_watchpost_open: true, ruins_watchpost_restored: true, ruins_watchpost_resolved: true };
base.signals = { ...base.signals, road_trouble: 1, north_mill_relief_stock: 2 };
base.actors.npc_gallery_brute.hp.current = 0;
base.actors.npc_gallery_brute.alive = false;
base.actors.npc_gallery_scout.hp.current = 0;
base.actors.npc_gallery_scout.alive = false;
assert.equal(can(base, 'act_gallery_read_watch_records'), true);
assert.equal(can(base, 'act_gallery_post_watch'), false, 'requires player-discovered records');
const discovered = run(base, P('act_gallery_read_watch_records'));
assert.equal(can(discovered, 'act_gallery_post_watch'), true);
assert.equal(can(discovered, 'act_gallery_take_cache'), true);
assert.equal(discovered.signals.ruins_raider_stage, 1, 'NPC patrol begins independently');
assert.deepEqual(save(discovered), discovered);
const protectedState = run(discovered, P('act_gallery_post_watch'));
const selfishState = run(discovered, P('act_gallery_take_cache'));
assert.equal(protectedState.flags.ruins_gallery_watch_posted, true);
assert.equal(selfishState.flags.ruins_gallery_cache_taken, true);
assert.equal(protectedState.flags.ruins_gallery_aftermath_resolved, true);
assert.equal(selfishState.flags.ruins_gallery_aftermath_resolved, true);
assert.equal(me(protectedState).money, me(discovered).money - 3);
assert.equal(me(selfishState).money, me(discovered).money + 6);
assert.equal(can(protectedState, 'act_gallery_take_cache'), false);
assert.equal(can(selfishState, 'act_gallery_post_watch'), false);
assert.deepEqual(save(protectedState), protectedState);
assert.deepEqual(save(selfishState), selfishState);
const defended = run(protectedState, { type: 'wait', minutes: 720 });
const exposed = run(selfishState, { type: 'wait', minutes: 720 });
assert.equal(defended.flags.ruins_gallery_watch_intercepted, true);
assert.equal(defended.flags.ruins_raider_cleared, true);
assert.equal(defended.actors.npc_ruins_raider.locationId, 'loc_ruins');
assert.equal(defended.signals.north_mill_relief_stock, 2, 'guard prevents theft of existing food');
assert.equal(exposed.actors.npc_ruins_raider.locationId, 'loc_village');
assert.equal(exposed.signals.north_mill_relief_stock, 1, 'unprotected village loses real food');
assert.equal(exposed.flags.ruins_raider_cleared, undefined);
assert.deepEqual(run(save(protectedState), { type: 'wait', minutes: 720 }), defended);
assert.deepEqual(run(save(selfishState), { type: 'wait', minutes: 720 }), exposed);
assert.equal(defended.rng.cursor, exposed.rng.cursor, 'choice and NPC response do not consume RNG');
assert.equal(JSON.stringify(view(initial, worldData)).includes('ruins_gallery_watch_intercepted'), false);
const heirStart = structuredClone(defended);
me(heirStart).alive = false;
heirStart.pending = { kind: 'newCharacter' };
const heir = run(heirStart, { type: 'startCharacter', templateId: 'start_wanderer' });
assert.equal(heir.flags.ruins_gallery_watch_posted, true);
assert.equal(heir.flags.ruins_raider_cleared, true);
assert.equal(me(heir).growth.growth_wanderer.unlocks?.unl_gallery_watch_records, undefined);
console.log('Gallery aftermath PASS: mutually exclusive post-combat choices, NPC interception vs ration theft, Save, determinism, heir knowledge');
