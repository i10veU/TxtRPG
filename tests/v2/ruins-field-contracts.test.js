import assert from 'node:assert/strict';
import { createInitialState, step, view, validateState, checkDataCompatibility } from '../../web/v2/core/engine.js';
import { buildSaveRecord, parseLoadedRecord } from '../../web/v2/storage/idb.js';
import { worldData } from '../../web/v2/data/world.js';
const P = actionId => ({ type: 'perform', actionId });
const me = s => s.actors[s.player.actorId];
const can = (s, id) => view(s, worldData).actions.some(a => a.actionId === id && a.available);
const act = (s, a) => {
  const r = step(s, a, worldData);
  assert.ok(!r.events.some(e => e.type === 'action.rejected'), JSON.stringify(r.events));
  assert.deepEqual(validateState(r.state), []);
  assert.deepEqual(checkDataCompatibility(r.state, worldData), []);
  return r.state;
};
const save = s => parseLoadedRecord(JSON.parse(JSON.stringify(buildSaveRecord('field-contracts-504', s, { savedAt: 1 }))));
const base = createInitialState({ worldSeed: 'field-contracts-504', data: worldData }).state;
me(base).locationId = 'loc_mill_hamlet';
me(base).inventory = { item_flour_sack: 2, item_mill_bread: 2, item_iron_sword: 1 };
me(base).loadout = { hand: 'item_iron_sword' };
me(base).growth.growth_wanderer.resources.stamina = { current: 20, max: 20 };
me(base).growth.growth_wanderer.unlocks = { unl_ford_master_surveyor: true };
base.signals = { ...base.signals, north_mill_relief_stock: 0, road_trouble: 2 };
const survey = 'act_mill_master_survey_relief', guard = 'act_mill_master_guard_caravan';
assert.ok(can(base, survey));
const supplied = act(base, P(survey));
assert.equal(supplied.signals.north_mill_relief_stock, 1);
assert.equal(me(supplied).inventory.item_flour_sack, 1);
assert.ok(!can(supplied, survey));
assert.deepEqual(act(save(base), P(survey)), supplied);
assert.deepEqual(supplied.rng, base.rng);
assert.ok(!JSON.stringify(view(base, worldData)).includes('ford_master_contract_used'));
const early = act(supplied, { type: 'wait', minutes: 1439 });
assert.ok(!can(early, survey));
const day = act(early, { type: 'wait', minutes: 1 });
assert.ok(can(day, survey));
const repeated = act(day, P(survey));
assert.equal(repeated.signals.north_mill_relief_stock, 2);
assert.equal(me(repeated).inventory.item_flour_sack ?? 0, 0);
assert.deepEqual(act(save(early), { type: 'wait', minutes: 1 }), day);
const full = structuredClone(base); full.signals.north_mill_relief_stock = 3;
assert.ok(!can(full, survey));
const v = structuredClone(base);
me(v).growth.growth_wanderer.unlocks = { unl_ford_master_vanguard: true };
v.flags = { ...v.flags, ruins_watchpost_open: true, ruins_watchpost_restored: true };
v.signals.ruins_raider_repulsions = 2; v.signals.ruins_raider_stage = 1;
assert.ok(can(v, guard) && !can(v, survey));
const guarded = act(v, P(guard));
const unguarded = act(v, { type: 'wait', minutes: 75 });
assert.equal(me(guarded).inventory.item_mill_bread, 1);
assert.ok(guarded.signals.road_trouble <= 1);
assert.equal(guarded.actors.npc_ruins_raider.locationId, 'loc_ruins_gallery');
assert.equal(unguarded.actors.npc_ruins_raider.locationId, 'loc_mill_hamlet');
assert.ok(!can(guarded, guard));
assert.deepEqual(act(save(v), P(guard)), guarded);
assert.deepEqual(guarded.rng, v.rng);
const novice = structuredClone(v);
delete me(novice).growth.growth_wanderer.unlocks.unl_ford_master_vanguard;
assert.ok(!can(novice, guard));
assert.ok(step(novice, P(guard), worldData).events.some(e => e.type === 'action.rejected'));
console.log('Field contracts PASS: 24h finite supply, NPC patrol divergence, Save/RNG/knowledge');
