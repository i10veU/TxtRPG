import assert from 'node:assert/strict';
import { createInitialState, step, view, validateState, checkDataCompatibility } from '../../web/v2/core/engine.js';
import { evaluateCondition } from '../../web/v2/core/rules.js';
import { buildSaveRecord, parseLoadedRecord } from '../../web/v2/storage/idb.js';
import { worldData } from '../../web/v2/data/world.js';
const me = s => s.actors[s.player.actorId];
const can = (s, id) => view(s, worldData).actions.some(a => a.actionId === id && a.available);
const link = (from, to) => worldData.locations[from].links.find(l => l.to === to).requires;
const allowed = (s, cond) => evaluateCondition(cond, { state: s, data: worldData, actorId: s.player.actorId, contextKind: 'player' });
const save = s => parseLoadedRecord(JSON.parse(JSON.stringify(buildSaveRecord('ruins-cellar', s, { savedAt: 1 }))));
const act = actionId => ({ type: 'perform', actionId });
function run(s, action) {
  const r = step(s, action, worldData);
  assert.ok(!r.events.some(e => e.type === 'action.rejected'), JSON.stringify(action));
  assert.deepEqual(validateState(r.state), []);
  assert.deepEqual(checkDataCompatibility(r.state, worldData), []);
  return r;
}
const start = createInitialState({ worldSeed: 'ruins-cellar-474', data: worldData }).state;
me(start).locationId = 'loc_ruins'; me(start).money = 12;
me(start).inventory.item_lantern = 1; me(start).inventory.item_relic = 1;
me(start).growth.growth_wanderer.skills = { investigation: 1 };
assert.equal(can(start, 'act_trace_ruins_cellar'), true);
assert.equal(allowed(start, link('loc_ruins', 'loc_ruins_cellar')), false);
assert.equal(allowed(start, link('loc_village', 'loc_ruins_cellar')), false);
const withoutRelic = structuredClone(start); me(withoutRelic).inventory.item_relic = 0;
assert.equal(can(withoutRelic, 'act_trace_ruins_cellar'), false);
let good, bad;
for (let seed = 1; seed <= 300 && (!good || !bad); seed++) {
  const before = structuredClone(start); before.rng.seed = seed;
  const r = run(before, act('act_trace_ruins_cellar'));
  const tier = r.events.find(e => e.type === 'check.resolved')?.data.tier;
  if (['great', 'success'].includes(tier)) good ??= { before, after: r.state };
  else bad ??= { before, after: r.state };
}
assert.ok(good && bad);
assert.equal(allowed(good.after, link('loc_ruins', 'loc_ruins_cellar')), true);
assert.equal(allowed(bad.after, link('loc_ruins', 'loc_ruins_cellar')), false);
assert.equal(can(bad.after, 'act_trace_ruins_cellar'), true);
assert.deepEqual(run(good.before, act('act_trace_ruins_cellar')).state, good.after);
assert.deepEqual(save(good.after), good.after);
const inside = run(good.after, { type: 'move', to: 'loc_ruins_cellar' }).state;
assert.equal(inside.time.minute - good.after.time.minute, 20);
assert.equal(can(inside, 'act_ruins_cellar_take_cache'), true);
assert.equal(can(inside, 'act_ruins_cellar_make_refuge'), true);
const loot = run(inside, act('act_ruins_cellar_take_cache')).state;
assert.equal(me(loot).money, me(inside).money + 8);
assert.equal(me(loot).inventory.item_mill_bread, 2);
assert.equal(can(loot, 'act_ruins_cellar_make_refuge'), false);
assert.equal(allowed(loot, link('loc_village', 'loc_ruins_cellar')), false);
assert.deepEqual(loot.rng, inside.rng); assert.deepEqual(save(loot), loot);
const refuge = run(inside, act('act_ruins_cellar_make_refuge')).state;
assert.equal(me(refuge).money, me(inside).money - 4);
assert.equal(refuge.flags.ruins_cellar_refuge, true);
assert.equal(can(refuge, 'act_ruins_cellar_take_cache'), false);
assert.equal(allowed(refuge, link('loc_village', 'loc_ruins_cellar')), true);
assert.deepEqual(refuge.rng, inside.rng);
const injured = structuredClone(refuge);
me(injured).hp.current = 4; me(injured).growth.growth_wanderer.resources.stamina.current = 1;
const rested = run(injured, act('act_rest_ruins_cellar_refuge')).state;
assert.equal(me(rested).hp.current, 8);
assert.equal(me(rested).growth.growth_wanderer.resources.stamina.current, 6);
assert.deepEqual(save(rested), rested);
const heirSeed = structuredClone(refuge); me(heirSeed).alive = false;
heirSeed.pending = { kind: 'newCharacter' };
const heir = run(heirSeed, { type: 'startCharacter', templateId: 'start_wanderer' }).state;
assert.equal(me(heir).growth.growth_wanderer.unlocks?.unl_ruins_cellar_route, undefined);
assert.equal(heir.flags.ruins_cellar_refuge, true);
assert.equal(allowed(heir, link('loc_village', 'loc_ruins_cellar')), true);
assert.equal(me(run(heir, { type: 'move', to: 'loc_ruins_cellar' }).state).locationId, 'loc_ruins_cellar');
console.log('Ruins cellar: personal map, finite branch, public refuge, successor, RNG, Save PASS');
