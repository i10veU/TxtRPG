import assert from 'node:assert/strict';
import { createInitialState, step, view, validateState, checkDataCompatibility } from '../../web/v2/core/engine.js';
import { buildSaveRecord, parseLoadedRecord } from '../../web/v2/storage/idb.js';
import { worldData } from '../../web/v2/data/world.js';

const action = actionId => ({ type: 'perform', actionId });
const me = s => s.actors[s.player.actorId];
const can = (s, id) => view(s, worldData).actions.some(a => a.actionId === id && a.available);
const run = (s, a) => {
  const result = step(s, a, worldData);
  assert.ok(!result.events.some(e => e.type === 'action.rejected'), JSON.stringify(result.events));
  assert.deepEqual(validateState(result.state), []);
  assert.deepEqual(checkDataCompatibility(result.state, worldData), []);
  return result.state;
};
const save = s => parseLoadedRecord(JSON.parse(JSON.stringify(buildSaveRecord('raider-sightings', s, { savedAt: 1 }))));
const base = createInitialState({ worldSeed: 'ruins-raider-sightings-480', data: worldData }).state;
base.flags = { ruins_watchpost_open: true, ruins_watchpost_restored: true, ruins_watchpost_resolved: true };
base.signals = { ...(base.signals ?? {}), road_trouble: 1, north_mill_relief_stock: 3 };
me(base).locationId = 'loc_village';
me(base).money = 10;
assert.equal(can(base, 'act_ruins_raider_ask_village_guard'), false);
assert.equal(can(base, 'act_ruins_raider_organize_sentries'), false);
assert.equal(JSON.stringify(view(base, worldData)).includes('rum_raider_village_sighting'), false);

const atWatch = run(base, { type: 'wait', minutes: 720 });
assert.equal(atWatch.actors.npc_ruins_raider.locationId, 'loc_ruins_watchpost');
assert.equal(atWatch.flags.ruins_raider_watchpost_recent, true);
assert.equal(atWatch.knowledge?.npc_ruins_watch_guard, undefined);
assert.equal(can(atWatch, 'act_ruins_raider_ask_village_guard'), false);
const atVillage = run(atWatch, { type: 'wait', minutes: 720 });
assert.equal(atVillage.flags.ruins_raider_watchpost_recent, false);
assert.equal(atVillage.flags.ruins_raider_village_recent, true);
assert.equal(atVillage.knowledge?.npc_ruins_village_guard, undefined);
assert.equal(can(atVillage, 'act_ruins_raider_ask_village_guard'), true);
assert.equal(can(atVillage, 'act_ruins_raider_organize_sentries'), false);
const told = run(atVillage, action('act_ruins_raider_ask_village_guard'));
const word = told.knowledge[told.player.actorId].rum_raider_village_sighting;
assert.equal(word.aboutDay, undefined, 'catch-up cannot invent a witness observation day');
assert.deepEqual(word.sources, ['npc_ruins_village_guard']);
assert.equal(told.flags.ruins_raider_village_report_current, true);
assert.equal(can(told, 'act_ruins_raider_organize_sentries'), true);
assert.deepEqual(save(told), told);
const organized = run(told, action('act_ruins_raider_organize_sentries'));
assert.equal(me(organized).money, me(told).money - 3);
assert.equal(organized.flags.ruins_raider_sentries_ready, true);
assert.equal(can(organized, 'act_ruins_raider_organize_sentries'), false);
assert.deepEqual(organized, run(told, action('act_ruins_raider_organize_sentries')));
const afterLeave = run(organized, { type: 'wait', minutes: 720 });
assert.equal(afterLeave.flags.ruins_raider_village_recent, false);
assert.equal(can(afterLeave, 'act_ruins_raider_organize_sentries'), false);
const afterWatch = run(afterLeave, { type: 'wait', minutes: 720 });
const beforeReturn = afterWatch.signals.north_mill_relief_stock;
const repelled = run(afterWatch, { type: 'wait', minutes: 720 });
assert.equal(repelled.actors.npc_ruins_raider.locationId, 'loc_ruins_gallery');
assert.equal(repelled.flags.ruins_raider_sentries_ready, false);
assert.equal(repelled.signals.north_mill_relief_stock, beforeReturn);
assert.equal(repelled.flags.ruins_raider_cleared, undefined);
assert.deepEqual(save(repelled), repelled);
const nextWatch = run(repelled, { type: 'wait', minutes: 720 });
const nextRaid = run(nextWatch, { type: 'wait', minutes: 720 });
assert.equal(nextRaid.signals.north_mill_relief_stock, beforeReturn - 1);
assert.equal(nextRaid.actors.npc_ruins_raider.locationId, 'loc_village');
assert.equal(nextRaid.flags.ruins_raider_village_report_current, false);
assert.equal(can(nextRaid, 'act_ruins_raider_organize_sentries'), false, 'old testimony cannot fund a new patrol');
assert.equal(can(run(nextRaid, action('act_ruins_raider_ask_village_guard')), 'act_ruins_raider_organize_sentries'), true);
const heir = run({ ...structuredClone(repelled), pending: { kind: 'newCharacter' } }, { type: 'startCharacter', templateId: 'start_wanderer' });
assert.equal(heir.flags.ruins_raider_sentries_ready, false);
assert.equal(heir.knowledge[heir.player.actorId]?.rum_raider_village_sighting, undefined);

// The watchpost witness remembers a genuine arrival; its source is distinct.
const watchReport = structuredClone(atVillage);
me(watchReport).locationId = 'loc_ruins_watchpost';
assert.equal(can(watchReport, 'act_ruins_raider_ask_watch_guard'), true);
const heardWatch = run(watchReport, action('act_ruins_raider_ask_watch_guard'));
assert.deepEqual(heardWatch.knowledge[heardWatch.player.actorId].rum_raider_watchpost_sighting.sources, ['npc_ruins_watch_guard']);
assert.equal(heardWatch.knowledge[heardWatch.player.actorId].rum_raider_watchpost_sighting.aboutDay, undefined);
console.log('Ruins raider: witnessed source/freshness, fresh militia response, delayed protection, recurring threat, Save, heir and projection PASS');
