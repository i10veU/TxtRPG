// Relief warehouse NPC shipments and optional player-funded dispatch; no new save schema.
import assert from 'node:assert/strict';
import { createInitialState, step, view, validateState, checkDataCompatibility } from '../../web/v2/core/engine.js';
import { buildSaveRecord, parseLoadedRecord } from '../../web/v2/storage/idb.js';
import { worldData } from '../../web/v2/data/world.js';

const A = s => s.actors[s.player.actorId];
const stock = s => s.signals?.north_waystation_stock ?? 0;
const village = s => s.signals?.north_mill_relief_stock ?? 0;
const can = (s, id) => view(s, worldData).actions.some(a => a.actionId === id && a.available);
const run = (s, action) => {
  const r = step(s, action, worldData);
  assert.equal(r.events.some(e => e.type === 'action.rejected'), false, JSON.stringify(action));
  assert.deepEqual(validateState(r.state), []);
  assert.deepEqual(checkDataCompatibility(r.state, worldData), []);
  return r.state;
};
const perform = actionId => ({ type: 'perform', actionId });
const wait = minutes => ({ type: 'wait', minutes });
const save = s => parseLoadedRecord(JSON.parse(JSON.stringify(buildSaveRecord('north-relief-wagon', s, { savedAt: 1 }))));
const initial = createInitialState({ worldSeed: 'north-relief-wagon-469', data: worldData }).state;
A(initial).locationId = 'loc_far_bank'; A(initial).money = 30;
initial.flags ??= {}; initial.flags.north_road_guided = true;
initial.flags.waystation_supply_delivered = true;
initial.flags.north_supply_relief_pact = true;
const first = run(initial, wait(1));
assert.equal(village(first), 1, 'a guided road with a standing pact starts NPC delivery');
assert.equal(stock(first), 1);
const day = run(first, wait(1440));
assert.equal(village(day), 2, 'NPC relief wagon restocks village daily');
assert.equal(stock(day), 2, 'one of two shipments transfers to village');
assert.equal(can(first, 'act_dispatch_north_relief_wagon'), true);
const dispatched = run(first, perform('act_dispatch_north_relief_wagon'));
assert.equal(village(dispatched), 2);
assert.equal(stock(dispatched), 0);
assert.equal(A(dispatched).money, A(first).money - 2);
assert.equal(can(dispatched, 'act_dispatch_north_relief_wagon'), false, 'cannot dispatch empty or overfill');
assert.deepEqual(dispatched.rng, first.rng);
const atMill = structuredClone(dispatched); A(atMill).locationId = 'loc_mill_hamlet';
assert.equal(can(atMill, 'act_buy_mill_relief_rations'), true);
const bought = run(atMill, perform('act_buy_mill_relief_rations'));
assert.equal(village(bought), 1);
assert.equal(A(bought).money, A(atMill).money - 1);
assert.equal(A(bought).inventory.item_mill_bread, (A(atMill).inventory.item_mill_bread ?? 0) + 2);
assert.deepEqual(bought.rng, atMill.rng);
assert.deepEqual(save(bought), bought);
assert.deepEqual(run(atMill, perform('act_buy_mill_relief_rations')), bought);
const capped = Array.from({length: 10}).reduce(s => run(s, wait(1440)), bought);
assert.equal(village(capped), 2, 'NPC deliveries cannot create unlimited village backlog');
assert.ok(stock(capped) <= 3, 'waystation stock remains capped');
const heirSeed = structuredClone(capped); A(heirSeed).alive = false; heirSeed.pending = {kind:'newCharacter'};
const heir = run(heirSeed, {type:'startCharacter', templateId:'start_wanderer'});
assert.equal(village(heir), 2, 'public village warehouse survives succession');
A(heir).locationId = 'loc_mill_hamlet'; A(heir).money = 5;
assert.equal(can(heir, 'act_buy_mill_relief_rations'), true);
const privateWorld = structuredClone(initial);
privateWorld.flags.north_supply_relief_pact = false;
privateWorld.flags.north_supply_private_sale = true;
const privateDay = run(run(privateWorld, wait(1)), wait(1440));
assert.equal(village(privateDay), 0, 'private contract does not create village warehouse');
assert.equal(can(privateDay, 'act_dispatch_north_relief_wagon'), false);
A(privateDay).locationId = 'loc_mill_hamlet';
assert.equal(can(privateDay, 'act_buy_mill_relief_rations'), false);
console.log('North relief wagon: autonomous transfers, manual dispatch, village rations, caps, private exclusion, Save, succession, RNG PASS');
