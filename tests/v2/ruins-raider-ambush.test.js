import assert from 'node:assert/strict';
import { createInitialState, step, view, validateState, checkDataCompatibility } from '../../web/v2/core/engine.js';
import { buildSaveRecord, parseLoadedRecord } from '../../web/v2/storage/idb.js';
import { worldData } from '../../web/v2/data/world.js';

const act = actionId => ({ type: 'perform', actionId });
const me = state => state.actors[state.player.actorId];
const can = (state, id) => view(state, worldData).actions.some(a => a.actionId === id && a.available);
const run = (state, action) => {
  const result = step(state, action, worldData);
  assert.ok(!result.events.some(e => e.type === 'action.rejected'), JSON.stringify(result.events));
  assert.deepEqual(validateState(result.state), []);
  assert.deepEqual(checkDataCompatibility(result.state, worldData), []);
  return result.state;
};
const save = s => parseLoadedRecord(JSON.parse(JSON.stringify(buildSaveRecord('raider-ambush', s, { savedAt: 1 }))));
const base = createInitialState({ worldSeed: 'ruins-raider-ambush-479', data: worldData }).state;
base.flags = { ruins_watchpost_open: true, ruins_watchpost_restored: true, ruins_watchpost_resolved: true };
base.signals = { ...(base.signals ?? {}), road_trouble: 1, north_mill_relief_stock: 2 };
me(base).locationId = 'loc_ruins_watchpost';
me(base).inventory.item_lantern = 1;
me(base).inventory.item_mill_bread = 5;
me(base).growth.growth_wanderer.skills = { investigation: 1 };
assert.equal(can(base, 'act_ruins_raider_read_tracks'), false);
const visited = run(base, { type: 'wait', minutes: 720 });
assert.equal(visited.actors.npc_ruins_raider.locationId, 'loc_ruins_watchpost');
assert.equal(visited.flags.ruins_raider_watchpost_tracks, true);
const away = run(visited, { type: 'wait', minutes: 720 });
assert.equal(away.actors.npc_ruins_raider.locationId, 'loc_village');
assert.equal(can(away, 'act_ruins_raider_read_tracks'), true);
assert.equal(can(away, 'act_ruins_raider_set_ambush'), false);
let observed;
for (let seed = 1; seed < 1000; seed++) {
  const before = structuredClone(away);
  before.rng.seed = seed;
  const result = step(before, act('act_ruins_raider_read_tracks'), worldData);
  if (['great', 'success'].includes(result.events.find(e => e.type === 'check.resolved')?.data.tier)) {
    observed = run(before, act('act_ruins_raider_read_tracks'));
    assert.deepEqual(observed, run(before, act('act_ruins_raider_read_tracks')));
    break;
  }
}
assert.ok(observed, 'a successful field observation must be reproducible');
assert.equal(can(observed, 'act_ruins_raider_set_ambush'), true);
assert.deepEqual(save(observed), observed);
const bread = me(observed).inventory.item_mill_bread;
const armed = run(observed, act('act_ruins_raider_set_ambush'));
assert.equal(armed.flags.ruins_raider_ambush_armed, true);
assert.equal(me(armed).inventory.item_mill_bread, bread - 2);
assert.equal(can(armed, 'act_ruins_raider_set_ambush'), false);
assert.deepEqual(save(armed), armed);
const returning = run(armed, { type: 'wait', minutes: 720 });
assert.equal(returning.actors.npc_ruins_raider.locationId, 'loc_ruins_gallery');
const captured = run(returning, { type: 'wait', minutes: 720 });
assert.equal(captured.flags.ruins_raider_ambush_caught, true);
assert.equal(captured.flags.ruins_raider_cleared, true);
assert.equal(captured.flags.ruins_raider_ambush_armed, false);
assert.equal(captured.actors.npc_ruins_raider.locationId, 'loc_ruins');
assert.equal(captured.actors.npc_ruins_raider.alive, true);
assert.deepEqual(run(returning, { type: 'wait', minutes: 720 }), captured);
assert.deepEqual(save(captured), captured);
const later = run(run(captured, { type: 'wait', minutes: 1440 }), { type: 'wait', minutes: 720 });
assert.equal(later.actors.npc_ruins_raider.locationId, 'loc_ruins');
const report = structuredClone(captured);
me(report).locationId = 'loc_village';
assert.equal(can(report, 'act_ruins_raider_claim_ambush'), true);
const rewarded = run(report, act('act_ruins_raider_claim_ambush'));
assert.equal(me(rewarded).money, me(report).money + 5);
assert.equal(can(rewarded, 'act_ruins_raider_claim_ambush'), false);
const heirState = structuredClone(rewarded);
me(heirState).alive = false;
heirState.pending = { kind: 'newCharacter' };
const heir = run(heirState, { type: 'startCharacter', templateId: 'start_wanderer' });
assert.equal(heir.flags.ruins_raider_ambush_caught, true);
assert.equal(heir.actors[heir.player.actorId].growth.growth_wanderer.unlocks?.unl_ruins_raider_tracked, undefined);
const warningState = structuredClone(observed);
me(warningState).locationId = 'loc_village';
const warned = run(warningState, act('act_ruins_raider_warn_village'));
assert.equal(warned.flags.ruins_raider_village_warned, true);
const nextRaid = structuredClone(warned);
nextRaid.signals.ruins_raider_stage = 1;
nextRaid.actors.npc_ruins_raider.locationId = 'loc_ruins_watchpost';
const avoided = run(nextRaid, { type: 'wait', minutes: 720 });
assert.equal(avoided.signals.north_mill_relief_stock, nextRaid.signals.north_mill_relief_stock);
assert.equal(avoided.flags.ruins_raider_village_warned, false);
assert.equal(avoided.actors.npc_ruins_raider.locationId, 'loc_ruins_gallery');
assert.equal(avoided.signals.ruins_raider_stage, 0);
assert.equal(avoided.flags.ruins_raider_cleared, undefined);
assert.deepEqual(save(avoided), avoided);
assert.equal(can(createInitialState({ worldSeed: 'hidden', data: worldData }).state, 'act_ruins_raider_set_ambush'), false);
console.log('Ruins raider: field tracks, delayed snare, finite reward, one-raid warning, deterministic replay, Save, heir, knowledge projection PASS');
