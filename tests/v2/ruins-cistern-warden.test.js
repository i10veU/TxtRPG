import assert from 'node:assert/strict';
import { createInitialState, step, view, validateState, checkDataCompatibility, adoptNewActors } from '../../web/v2/core/engine.js';
import { buildSaveRecord, parseLoadedRecord } from '../../web/v2/storage/idb.js';
import { worldData } from '../../web/v2/data/world.js';
const P = actionId => ({ type: 'perform', actionId });
const hero = s => s.actors[s.player.actorId];
const available = (s, id) => view(s, worldData).actions.some(a => a.actionId === id && a.available);
const saved = s => parseLoadedRecord(JSON.parse(JSON.stringify(buildSaveRecord('cistern-warden', s, { savedAt: 1 }))));
function play(s, action) {
  const r = step(s, action, worldData);
  assert.equal(r.events.some(e => e.type === 'action.rejected'), false, JSON.stringify(r.events));
  assert.deepEqual(validateState(r.state), []);
  assert.deepEqual(checkDataCompatibility(r.state, worldData), []);
  return r.state;
}
const initial = createInitialState({ worldSeed: 'cistern-warden-500', data: worldData }).state;
assert.ok(initial.actors.npc_cistern_warden, 'the new opponent must be a physical actor');
assert.equal(available(initial, 'act_cistern_warden_observe'), false, 'distant players cannot see the foe');
const base = structuredClone(initial);
hero(base).locationId = 'loc_ruins_cistern';
hero(base).inventory.item_lantern = 1;
hero(base).inventory.item_iron_sword = 1;
hero(base).loadout = { hand: 'item_iron_sword' };
hero(base).growth.growth_wanderer.skills = { investigation: 2, swordsmanship: 5 };
hero(base).growth.growth_wanderer.stats.str = 20;
hero(base).growth.growth_wanderer.stats.dex = 20;
hero(base).growth.growth_wanderer.resources.stamina = { current: 50, max: 50 };
base.flags = { ...base.flags, ruins_cistern_sluice_open: true };
assert.ok(available(base, 'act_cistern_warden_observe'));
assert.equal(available(base, 'act_cistern_warden_flow_counter'), false, 'flow counter must require personal water knowledge');
const studied = play(base, P('act_cistern_read_side_current'));
assert.equal(available(studied, 'act_cistern_warden_flow_counter'), false, 'correct stance is also required');
const observed = play(studied, P('act_cistern_warden_observe'));
assert.deepEqual(observed.rng, studied.rng, 'observation does not roll RNG');
const wrong = play(observed, P('act_cistern_warden_quick'));
assert.equal(hero(wrong).hp.current, hero(observed).hp.current - 2, 'wrong response is punished');
assert.equal(wrong.signals.cistern_warden_stance, 1);
assert.equal(available(wrong, 'act_cistern_warden_flow_counter'), true);
const beforeFlow = wrong.actors.npc_cistern_warden.hp.current;
const countered = play(wrong, P('act_cistern_warden_flow_counter'));
assert.equal(countered.actors.npc_cistern_warden.hp.current, beforeFlow - 2);
assert.deepEqual(countered.rng, wrong.rng, 'studied footing is a deterministic low-damage alternative');
assert.equal(countered.signals.cistern_warden_stance, 0);
assert.deepEqual(play(saved(wrong), P('act_cistern_warden_flow_counter')), countered);
assert.equal(available(base, 'act_cistern_warden_flow_counter'), false);
let s = countered;
for (let n = 0; n < 20 && s.actors.npc_cistern_warden.alive; n++) {
  const stance = s.signals.cistern_warden_stance ?? 0;
  const action = stance === 0 ? 'act_cistern_warden_heavy' : 'act_cistern_warden_flow_counter';
  s = play(s, P(action));
}
assert.equal(s.actors.npc_cistern_warden.alive, false);
assert.equal(s.flags.ruins_cistern_warden_defeated, true);
assert.equal(available(s, 'act_cistern_warden_heavy'), false);
assert.ok(available(s, 'act_cistern_warden_salvage'));
const salvaged = play(s, P('act_cistern_warden_salvage'));
assert.equal(salvaged.flags.ruins_cistern_warden_records_claimed, true);
assert.equal(available(salvaged, 'act_cistern_warden_salvage'), false);
assert.deepEqual(saved(salvaged), salvaged);
const heirStart = structuredClone(salvaged);
hero(heirStart).alive = false;
heirStart.pending = { kind: 'newCharacter' };
const heir = play(heirStart, { type: 'startCharacter', templateId: 'start_wanderer' });
assert.equal(heir.flags.ruins_cistern_warden_defeated, true);
assert.equal(heir.flags.ruins_cistern_warden_records_claimed, true);
assert.equal(available(heir, 'act_cistern_warden_salvage'), false);
const oldSave = structuredClone(initial);
delete oldSave.actors.npc_cistern_warden;
assert.ok(adoptNewActors(oldSave, worldData).state.actors.npc_cistern_warden);
assert.equal(JSON.stringify(view(initial, worldData)).includes('cistern_warden_stance'), false);
console.log('Cistern warden PASS: two tells, water knowledge counterplay, finite salvage, deterministic Save, successor, legacy actor');
