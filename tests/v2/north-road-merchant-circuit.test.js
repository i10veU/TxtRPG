// Public road improvements create a timed merchant circuit, not free unlimited goods.
import assert from 'node:assert/strict';
import { createInitialState, step, view, validateState, checkDataCompatibility } from '../../web/v2/core/engine.js';
import { buildSaveRecord, parseLoadedRecord } from '../../web/v2/storage/idb.js';
import { worldData } from '../../web/v2/data/world.js';

const A = s => s.actors[s.player.actorId];
const can = (s, id) => view(s, worldData).actions.some(a => a.actionId === id && a.available);
const rejected = r => r.events.some(e => e.type === 'action.rejected');
const run = (s, action) => {
  const r = step(s, action, worldData);
  assert.equal(rejected(r), false, JSON.stringify(action));
  assert.deepEqual(validateState(r.state), []);
  assert.deepEqual(checkDataCompatibility(r.state, worldData), []);
  return r.state;
};
const P = actionId => ({ type: 'perform', actionId });
const W = minutes => ({ type: 'wait', minutes });
const stock = s => s.signals?.north_waystation_stock ?? 0;
const trust = s => s.signals?.north_waystation_reliability ?? 0;
const save = s => parseLoadedRecord(JSON.parse(JSON.stringify(buildSaveRecord('merchant-circuit', s, { savedAt: 1 }))));
const initial = createInitialState({ worldSeed: 'merchant-circuit-467', data: worldData }).state;
A(initial).locationId = 'loc_far_bank'; A(initial).money = 30;
A(initial).inventory.item_mill_bread = 0;
initial.flags ??= {}; initial.flags.waystation_supply_delivered = true;
const unguided = run(initial, W(1));
assert.equal(stock(unguided), 0);
assert.equal(can(unguided, 'act_buy_waystation_bulk_rations'), false);
assert.equal(can(unguided, 'act_escort_north_merchant'), false);
const guided = structuredClone(initial); guided.flags.north_road_guided = true;
const first = run(guided, W(1));
assert.equal(stock(first), 1, 'merchant restocks when the improved road opens');
assert.equal(can(first, 'act_buy_waystation_bulk_rations'), true);
assert.equal(can(first, 'act_escort_north_merchant'), true);
const firstBuy = run(first, P('act_buy_waystation_bulk_rations'));
assert.equal(stock(firstBuy), 0);
assert.equal(A(firstBuy).money, A(first).money - 3);
assert.equal(A(firstBuy).inventory.item_mill_bread, 3);
assert.equal(can(firstBuy, 'act_buy_waystation_bulk_rations'), false);
assert.deepEqual(firstBuy.rng, first.rng);
const replenished = run(firstBuy, W(1440));
assert.equal(stock(replenished), 1, 'stock replenishes after a day');
let s = run(first, P('act_escort_north_merchant'));
assert.equal(stock(s), 0);
assert.equal(trust(s), 1);
assert.equal(A(s).money, A(first).money + 3);
assert.equal(can(s, 'act_escort_north_merchant'), false);
s = run(s, W(1440));
s = run(s, P('act_escort_north_merchant'));
assert.equal(trust(s), 2, 'two guarded shipments establish public merchant trust');
assert.equal(stock(s), 0);
assert.equal(can(s, 'act_buy_waystation_bulk_rations'), false);
s = run(s, W(1440));
assert.equal(stock(s), 1);
const beforeDiscount = s;
const discounted = run(s, P('act_buy_waystation_bulk_rations'));
assert.equal(A(discounted).money, A(beforeDiscount).money - 2, 'publicly reliable road reduces ration bundle price');
assert.equal(A(discounted).inventory.item_mill_bread, 3);
assert.deepEqual(save(discounted), discounted);
assert.deepEqual(discounted, run(beforeDiscount, P('act_buy_waystation_bulk_rations')));
const heirSeed = structuredClone(beforeDiscount);
A(heirSeed).alive = false; heirSeed.pending = { kind: 'newCharacter' };
const heir = run(heirSeed, { type: 'startCharacter', templateId: 'start_wanderer' });
A(heir).locationId = 'loc_far_bank'; A(heir).money = 10;
assert.equal(trust(heir), 2);
assert.equal(can(heir, 'act_buy_waystation_bulk_rations'), true);
const heirBuy = run(heir, P('act_buy_waystation_bulk_rations'));
assert.equal(A(heirBuy).money, 8);
const afterLong = [1, 2, 3].reduce(s => run(s, W(1440)), beforeDiscount);
assert.equal(stock(afterLong), 3, 'stock is capped even across multi-day travel');
assert.deepEqual(afterLong.rng, beforeDiscount.rng);
console.log('North road merchant circuit: timed stock, escort, discount, save, succession, deterministic RNG PASS');
