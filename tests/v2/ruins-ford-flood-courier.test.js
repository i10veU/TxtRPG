import assert from 'node:assert/strict';
import { createInitialState, step, view, validateState, checkDataCompatibility, adoptNewActors } from '../../web/v2/core/engine.js';
import { buildSaveRecord, parseLoadedRecord } from '../../web/v2/storage/idb.js';
import { worldData } from '../../web/v2/data/world.js';

const P = actionId => ({ type: 'perform', actionId });
const me = s => s.actors[s.player.actorId];
const can = (s, id) => view(s, worldData).actions.some(a => a.actionId === id && a.available);
const save = s => parseLoadedRecord(JSON.parse(JSON.stringify(buildSaveRecord('ford-flood-501', s, { savedAt: 1 }))));
function play(s, action) {
  const r = step(s, action, worldData);
  assert.equal(r.events.some(e => e.type === 'action.rejected'), false, JSON.stringify(r.events));
  assert.deepEqual(validateState(r.state), []);
  assert.deepEqual(checkDataCompatibility(r.state, worldData), []);
  return r.state;
}
const start = createInitialState({ worldSeed: 'ford-flood-501', data: worldData }).state;
assert.ok(start.actors.npc_ford_grain_runner, 'physical courier should exist with finite cargo');
assert.equal(start.actors.npc_ford_grain_runner.inventory.item_waystation_supply_crate, 1);
assert.equal(can(start, 'act_cistern_decode_flood_records'), false);
const base = structuredClone(start);
me(base).locationId = 'loc_ruins_cistern';
me(base).inventory.item_lantern = 1;
me(base).money = 10;
me(base).growth.growth_wanderer.skills = { investigation: 2 };
me(base).growth.growth_wanderer.resources.stamina = { current: 20, max: 20 };
base.flags = { ...base.flags, ruins_cistern_warden_records_claimed: true };
base.signals = { ...base.signals, north_mill_relief_stock: 0 };
const decoded = play(base, P('act_cistern_decode_flood_records'));
assert.equal(can(decoded, 'act_cistern_decode_flood_records'), false);
assert.deepEqual(decoded.rng, base.rng);
const atFord = structuredClone(decoded);
me(atFord).locationId = 'loc_river_ford';
assert.equal(can(atFord, 'act_ford_build_flood_beacons'), false);
const surveyed = play(atFord, P('act_ford_survey_flood_route'));
assert.ok(can(surveyed, 'act_ford_build_flood_beacons'));
assert.ok(can(surveyed, 'act_ford_salvage_flood_tools'));
const protectedState = play(surveyed, P('act_ford_build_flood_beacons'));
const selfishState = play(surveyed, P('act_ford_salvage_flood_tools'));
assert.equal(me(protectedState).money, me(surveyed).money - 3);
assert.equal(me(selfishState).money, me(surveyed).money + 5);
assert.equal(can(protectedState, 'act_ford_salvage_flood_tools'), false);
assert.equal(can(selfishState, 'act_ford_build_flood_beacons'), false);
assert.equal(protectedState.signals.ford_flood_stage, 1);
assert.equal(selfishState.signals.ford_flood_stage, 1);
assert.equal(protectedState.actors.npc_ford_grain_runner.locationId, 'loc_river_ford');
assert.deepEqual(save(protectedState), protectedState);
const safe = play(protectedState, { type: 'wait', minutes: 720 });
const lost = play(selfishState, { type: 'wait', minutes: 720 });
assert.equal(safe.actors.npc_ford_grain_runner.locationId, 'loc_mill_hamlet');
assert.equal(safe.actors.npc_ford_grain_runner.inventory.item_waystation_supply_crate, 1);
assert.equal(lost.actors.npc_ford_grain_runner.locationId, 'loc_crossroads');
assert.equal(lost.actors.npc_ford_grain_runner.inventory.item_waystation_supply_crate ?? 0, 0);
assert.equal(safe.flags.ford_flood_resolved, true);
assert.equal(lost.flags.ford_flood_resolved, true);
assert.equal(can(safe, 'act_mill_unload_ford_courier'), false, 'the player must meet the courier in person');
const atMill = structuredClone(safe);
me(atMill).locationId = 'loc_mill_hamlet';
assert.ok(can(atMill, 'act_mill_unload_ford_courier'));
const delivered = play(atMill, P('act_mill_unload_ford_courier'));
assert.equal(delivered.signals.north_mill_relief_stock, atMill.signals.north_mill_relief_stock + 1);
assert.equal(delivered.actors.npc_ford_grain_runner.inventory.item_waystation_supply_crate ?? 0, 0);
assert.equal(can(delivered, 'act_mill_unload_ford_courier'), false);
assert.deepEqual(play(save(atMill), P('act_mill_unload_ford_courier')), delivered);
assert.deepEqual(play(save(protectedState), { type: 'wait', minutes: 720 }), safe);
assert.deepEqual(play(save(selfishState), { type: 'wait', minutes: 720 }), lost);
const midWait = play(protectedState, { type: 'wait', minutes: 360 });
assert.equal(midWait.actors.npc_ford_grain_runner.locationId, 'loc_river_ford', 'the courier must not teleport early');
assert.deepEqual(play(save(midWait), { type: 'wait', minutes: 360 }), safe, 'split wait and restored clock must agree');
const fullWarehouse = structuredClone(atMill);
fullWarehouse.signals.north_mill_relief_stock = 3;
assert.equal(can(fullWarehouse, 'act_mill_unload_ford_courier'), false, 'full warehouse preserves the physical crate');
assert.equal(fullWarehouse.actors.npc_ford_grain_runner.inventory.item_waystation_supply_crate, 1);
assert.deepEqual(safe.rng, lost.rng);
const heirStart = structuredClone(safe);
me(heirStart).alive = false;
heirStart.pending = { kind: 'newCharacter' };
const heir = play(heirStart, { type: 'startCharacter', templateId: 'start_wanderer' });
assert.equal(heir.flags.ford_flood_resolved, true);
assert.equal(me(heir).growth.growth_wanderer.unlocks?.unl_ford_flood_route, undefined);
const legacy = structuredClone(start);
delete legacy.actors.npc_ford_grain_runner;
assert.ok(adoptNewActors(legacy, worldData).state.actors.npc_ford_grain_runner);
assert.equal(JSON.stringify(view(start, worldData)).includes('ford_flood_stage'), false);
console.log('Ford flood courier PASS: learned record, fork, 12h autonomous travel, finite NPC cargo, Save/heir/legacy, no private projection');
