import assert from 'node:assert/strict';
import { createInitialState, step, view, validateState, checkDataCompatibility } from '../../web/v2/core/engine.js';
import { buildSaveRecord, parseLoadedRecord } from '../../web/v2/storage/idb.js';
import { worldData } from '../../web/v2/data/world.js';
const P = actionId => ({ type: 'perform', actionId });
const me = s => s.actors[s.player.actorId];
const can = (s, id) => view(s, worldData).actions.some(a => a.actionId === id && a.available);
const play = (s, action) => {
  const r = step(s, action, worldData);
  assert.ok(!r.events.some(e => e.type === 'action.rejected'), JSON.stringify(r.events));
  assert.deepEqual(validateState(r.state), []);
  assert.deepEqual(checkDataCompatibility(r.state, worldData), []);
  return r.state;
};
const saved = s => parseLoadedRecord(JSON.parse(JSON.stringify(buildSaveRecord('guide-veteran', s, { savedAt: 1 }))));
const start = createInitialState({ worldSeed: 'guide-veteran-484', data: worldData }).state;
start.flags = { north_road_guided: true, ruins_raider_cleared: true, ruins_raider_guide_recruited: true };
start.signals = { ...start.signals, north_trade_stage: 1, north_trade_stock: 2, road_trouble: 2 };
start.actors.npc_ruins_raider.locationId = 'loc_river_ford';
me(start).locationId = 'loc_river_ford';
me(start).inventory.item_mill_bread = 9;
me(start).inventory.item_lantern = 1;
me(start).money = 15;
me(start).growth.growth_wanderer.skills = { investigation: 1 };
me(start).growth.growth_wanderer.stats.per = 30;
const board = s => play(s, P('act_ruins_guide_board_convoy'));
const scout = s => play(s, P('act_ruins_guide_scout_convoy'));
const first = scout(board(start));
assert.equal(first.signals.ruins_guide_experience, 1);
assert.equal(can(first, 'act_ruins_guide_establish_waymarks'), false);
const secondStart = structuredClone(first);
secondStart.signals.north_trade_stage = 1;
secondStart.signals.road_trouble = 2;
secondStart.flags.ruins_guide_on_convoy = false;
secondStart.actors.npc_ruins_raider.locationId = 'loc_river_ford';
me(secondStart).locationId = 'loc_river_ford';
me(secondStart).growth.growth_wanderer.resources.stamina.current = 6;
const second = scout(board(secondStart));
assert.equal(second.signals.ruins_guide_experience, 2);
assert.equal(can(second, 'act_ruins_guide_establish_waymarks'), true);
const built = play(second, P('act_ruins_guide_establish_waymarks'));
assert.equal(built.flags.ruins_guide_waymarks, true);
assert.equal(built.signals.road_trouble, 0);
assert.equal(me(built).money, me(second).money - 4);
assert.equal(me(built).inventory.item_mill_bread, me(second).inventory.item_mill_bread - 2);
assert.equal(can(built, 'act_ruins_guide_establish_waymarks'), false);
assert.deepEqual(saved(built), built);
assert.deepEqual(built, play(second, P('act_ruins_guide_establish_waymarks')));
const veteranStart = structuredClone(built);
veteranStart.signals.north_trade_stage = 1;
veteranStart.signals.road_trouble = 2;
veteranStart.flags.ruins_guide_on_convoy = false;
veteranStart.actors.npc_ruins_raider.locationId = 'loc_river_ford';
me(veteranStart).locationId = 'loc_river_ford';
const boarded = board(veteranStart);
assert.equal(can(boarded, 'act_ruins_guide_veteran_crossing'), true);
const crossed = play(boarded, P('act_ruins_guide_veteran_crossing'));
assert.equal(crossed.signals.north_trade_stage, 2);
assert.equal(crossed.signals.road_trouble, 1);
assert.equal(crossed.signals.ruins_guide_experience, 3);
assert.equal(me(crossed).money, me(boarded).money);
assert.equal(crossed.rng.cursor, boarded.rng.cursor);
assert.equal(crossed.actors.npc_ruins_raider.locationId, 'loc_mill_hamlet');
assert.deepEqual(saved(crossed), crossed);
assert.deepEqual(crossed, play(boarded, P('act_ruins_guide_veteran_crossing')));
assert.equal(JSON.stringify(view(crossed, worldData)).includes('npc_ruins_raider'), false);
const capped = structuredClone(boarded);
capped.signals.ruins_guide_experience = 3;
assert.equal(play(capped, P('act_ruins_guide_veteran_crossing')).signals.ruins_guide_experience, 3);
const auto = structuredClone(boarded);
auto.flags.ruins_guide_waymarks = false;
auto.signals.ruins_guide_experience = 0;
auto.signals.road_trouble = 0;
const arrived = play(auto, { type: 'wait', minutes: 1440 });
assert.equal(arrived.signals.ruins_guide_experience, 1);
const returned = play(arrived, { type: 'wait', minutes: 1440 });
assert.equal(returned.flags.ruins_guide_on_convoy, false);
const again = structuredClone(returned);
again.flags.ruins_guide_on_convoy = true;
again.signals.north_trade_stage = 1;
again.actors.npc_ruins_raider.locationId = 'loc_far_bank';
me(again).locationId = 'loc_far_bank';
assert.equal(play(again, { type: 'wait', minutes: 1440 }).signals.ruins_guide_experience, 2);
assert.deepEqual(saved(returned), returned);
console.log('Guide veteran: bounded career, waymarks, safe convoy, repeatable autonomy, Save, RNG PASS');
