import assert from 'node:assert/strict';
import { createInitialState, step, view, validateState, checkDataCompatibility } from '../../web/v2/core/engine.js';
import { buildSaveRecord, parseLoadedRecord } from '../../web/v2/storage/idb.js';
import { worldData } from '../../web/v2/data/world.js';
const P = actionId => ({ type: 'perform', actionId });
const me = s => s.actors[s.player.actorId];
const can = (s, id) => view(s, worldData).actions.some(a => a.actionId === id && a.available);
const play = (s, a) => {
  const r = step(s, a, worldData);
  assert.equal(r.events.some(e => e.type === 'action.rejected'), false, JSON.stringify(r.events));
  assert.deepEqual(validateState(r.state), []);
  assert.deepEqual(checkDataCompatibility(r.state, worldData), []);
  return r.state;
};
const save = s => parseLoadedRecord(JSON.parse(JSON.stringify(buildSaveRecord('field-disciplines-502', s, { savedAt: 1 }))));
const base = createInitialState({ worldSeed: 'field-disciplines-502', data: worldData }).state;
me(base).locationId = 'loc_mill_hamlet';
me(base).money = 12;
me(base).inventory.item_iron_sword = 1;
me(base).loadout = { hand: 'item_iron_sword' };
me(base).growth.growth_wanderer.skills = { investigation: 2, swordsmanship: 2 };
me(base).growth.growth_wanderer.unlocks = { unl_cistern_flood_chart: true, unl_ford_flood_route: true };
me(base).growth.growth_wanderer.resources.stamina = { current: 20, max: 20 };
assert.ok(can(base, 'act_mill_join_ford_surveyors') && can(base, 'act_mill_join_ford_vanguard'));
const scout = play(base, P('act_mill_join_ford_surveyors'));
const guard = play(base, P('act_mill_join_ford_vanguard'));
assert.ok(!can(scout, 'act_mill_join_ford_vanguard') && !can(guard, 'act_mill_join_ford_surveyors'));
assert.deepEqual(play(save(base), P('act_mill_join_ford_surveyors')), scout);
assert.deepEqual(play(save(base), P('act_mill_join_ford_vanguard')), guard);
const ford = s => { const c = structuredClone(s); me(c).locationId = 'loc_river_ford'; return c; };
const scoutFord = ford(scout), guardFord = ford(guard);
assert.ok(can(scoutFord, 'act_ford_surveyor_mark_safe_current'));
assert.ok(can(guardFord, 'act_ford_vanguard_escort_runner'));
assert.ok(!can(scoutFord, 'act_ford_vanguard_escort_runner'));
assert.ok(!can(guardFord, 'act_ford_surveyor_mark_safe_current'));
const marked = play(scoutFord, P('act_ford_surveyor_mark_safe_current'));
const escorted = play(guardFord, P('act_ford_vanguard_escort_runner'));
assert.equal(marked.flags.ford_flood_beacons, true);
assert.equal(escorted.flags.ford_flood_guarded, true);
assert.equal(escorted.flags.ford_flood_beacons, undefined);
assert.equal(me(marked).money, me(scoutFord).money - 1);
assert.equal(me(escorted).money, me(guardFord).money);
for (const s of [marked, escorted]) {
  const next = play(s, { type: 'wait', minutes: 720 });
  assert.equal(next.flags.ford_flood_courier_safe, true);
  assert.equal(next.actors.npc_ford_grain_runner.locationId, 'loc_mill_hamlet');
  assert.equal(next.actors.npc_ford_grain_runner.inventory.item_waystation_supply_crate, 1);
  assert.deepEqual(play(save(s), { type: 'wait', minutes: 720 }), next);
}
assert.deepEqual(marked.rng, scoutFord.rng);
assert.deepEqual(escorted.rng, guardFord.rng);
assert.ok(can(marked, 'act_ford_surveyor_follow_waymarks'));
assert.ok(!can(escorted, 'act_ford_surveyor_follow_waymarks'));
const crossed = play(marked, P('act_ford_surveyor_follow_waymarks'));
assert.equal(me(crossed).locationId, 'loc_mill_hamlet');
assert.equal(crossed.time.minute, marked.time.minute + 25);
const returned = play(crossed, P('act_mill_surveyor_return_waymarks'));
assert.equal(me(returned).locationId, 'loc_river_ford');
assert.deepEqual(returned.rng, marked.rng);
const duel = structuredClone(guard);
me(duel).locationId = 'loc_ruins_cistern';
me(duel).inventory.item_lantern = 1;
duel.flags = { ruins_cistern_sluice_open: true };
duel.signals = { cistern_warden_stance: 0 };
assert.ok(can(duel, 'act_cistern_warden_vanguard_parry'));
const countered = play(duel, P('act_cistern_warden_vanguard_parry'));
assert.equal(countered.actors.npc_cistern_warden.hp.current, duel.actors.npc_cistern_warden.hp.current - 3);
assert.deepEqual(countered.rng, duel.rng);
const sweep = structuredClone(duel); sweep.signals.cistern_warden_stance = 1;
assert.ok(!can(sweep, 'act_cistern_warden_vanguard_parry'));
const heirStart = play(marked, { type: 'wait', minutes: 720 });
me(heirStart).alive = false; heirStart.pending = { kind: 'newCharacter' };
const heir = play(heirStart, { type: 'startCharacter', templateId: 'start_wanderer' });
assert.equal(me(heir).growth.growth_wanderer.unlocks?.unl_ford_surveyor, undefined);
assert.equal(heir.flags.ford_flood_beacons, true);
assert.ok(!JSON.stringify(view(base, worldData)).includes('ford_flood_stage'));
console.log('Field disciplines PASS: exclusive careers, rescue fork, durable waymarks, combat, Save/RNG/heir');
