const fs = require("fs");
const path = require("path");
const vm = require("vm");
const assert = require("assert");

const root = path.resolve(__dirname, "..");
const files = ["web/core/game-state.js","web/data/places.js","web/data/npcs.js","web/data/cases.js","web/core/faction-world.js","web/core/economy-world.js","web/core/organization-world.js","web/core/npc-goals.js","web/core/organization-relations.js","web/core/action-resolver.js","web/core/npc-simulation.js"];
const context = { window: {}, console, Math, JSON, Object, Array, String, Number, Boolean, Date };
context.window = context;
vm.createContext(context);
for (const file of files) vm.runInContext(fs.readFileSync(path.join(root, file), "utf8"), context, { filename: file });
const RPG = context.AnonymousRPG;
assert(RPG && RPG.Core && RPG.Data);
const state = RPG.Core.createDefaultState(RPG.Data.npcs);
RPG.Core.ensureEconomy(state); RPG.Core.ensureOrganizations(state); RPG.Core.ensureOrganizationRelations(state); RPG.Core.ensureNPCGoals(state);
const before = Object.fromEntries(Object.entries(state.world.organizationRelations).map(([key, value]) => [key, value.score]));
const mediate = RPG.Data.caseDefinitions["faction-conflict"].choices.find((choice) => choice.id === "mediate");
assert(mediate.run(state).includes("대표들이"));
assert(Object.keys(before).every((key) => state.world.organizationRelations[key].score > before[key]));
assert(state.world.organizations.merchants.goalPressure >= 1);
const side = RPG.Data.caseDefinitions["faction-conflict"].choices.find((choice) => choice.id === "side");
const sideBefore = state.world.organizationRelations["merchants:rural"].score;
side.run(state);
assert(state.world.organizationRelations["merchants:rural"].score < sideBefore);
const expose = RPG.Data.caseDefinitions["faction-conflict"].choices.find((choice) => choice.id === "expose");
const archiveBefore = state.world.organizationRelations["archive:innkeepers"].score;
expose.run(state);
assert(state.world.organizationRelations["archive:innkeepers"].score > archiveBefore);
assert(state.world.organizations.archive.goalPressure >= 2);
const normalized = RPG.Core.normalizeState(state);
RPG.Core.ensureOrganizationRelations(normalized);
assert.strictEqual(Object.keys(normalized.world.organizationRelations).length, 3);
console.log("Phase 267 case consequence bridge: PASS");